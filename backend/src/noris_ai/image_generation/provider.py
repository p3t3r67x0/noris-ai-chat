"""Provider-independent image generation contract (P8 foundation).

No image endpoint, account entitlement, price or remote cancellation is implied.
The runtime must verify allowlisted capabilities, money limits and ownership
before calling a provider. Generated bytes must pass AttachmentService validation.
"""

from collections.abc import AsyncIterator
from decimal import Decimal
from typing import Literal, Protocol

from pydantic import BaseModel, ConfigDict, Field, model_validator
from typing_extensions import Self


class ImageSchema(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)


class ImageCapabilities(ImageSchema):
    provider_id: str = Field(min_length=1, max_length=120)
    model_id: str = Field(min_length=1, max_length=200)
    evidence: Literal["documented", "verified", "unknown"] = "unknown"
    sizes: tuple[str, ...] = ()
    qualities: tuple[str, ...] = ()
    formats: tuple[Literal["png", "jpeg"], ...] = ()
    max_count: int = Field(default=1, ge=1, le=8)
    timeout_seconds: int = Field(default=120, ge=1, le=3600)
    price_upper_bound_usd: Decimal | None = Field(default=None, ge=0, allow_inf_nan=False)
    price_source: str | None = Field(default=None, max_length=500)
    supports_cancel: bool = False
    supports_idempotency: bool = False

    @property
    def ready_for_admission(self) -> bool:
        return (
            self.evidence == "verified"
            and bool(self.sizes and self.formats)
            and self.price_upper_bound_usd is not None
            and bool(self.price_source)
        )


class ImageInput(ImageSchema):
    prompt: str = Field(min_length=1, max_length=16000)
    model_id: str = Field(min_length=1, max_length=200)
    size: str = Field(min_length=1, max_length=40)
    quality: str | None = Field(default=None, max_length=40)
    output_format: Literal["png", "jpeg"] = "png"
    count: int = Field(default=1, ge=1, le=8)

    @model_validator(mode="after")
    def nonblank_prompt(self) -> Self:
        if not self.prompt.strip():
            raise ValueError("Image prompt must not be blank")
        return self


class ProviderContext(ImageSchema):
    request_id: str = Field(min_length=1, max_length=128)
    deadline_seconds: int = Field(ge=1, le=3600)


class ImageOutput(ImageSchema):
    content: bytes = Field(min_length=1, max_length=20_000_000)
    mime_type: Literal["image/png", "image/jpeg"]
    model_id: str = Field(min_length=1, max_length=200)
    revised_prompt: str | None = Field(default=None, max_length=16000)
    operation_id: str | None = Field(default=None, max_length=200)
    measured_cost_usd: Decimal | None = Field(default=None, ge=0, allow_inf_nan=False)


class ProviderOperation(ImageSchema):
    state: Literal["queued", "running", "succeeded", "failed", "unknown", "unsupported"]


class CancellationOutcome(ImageSchema):
    state: Literal["cancelled", "not_cancelled", "unknown", "unsupported"]


class ImageProvider(Protocol):
    async def capabilities(self) -> tuple[ImageCapabilities, ...]: ...

    async def generate(self, request: ImageInput, context: ProviderContext) -> ImageOutput: ...

    async def inspect(self, operation_id: str) -> ProviderOperation: ...

    async def cancel(self, operation_id: str) -> CancellationOutcome: ...

    async def aclose(self) -> None: ...
