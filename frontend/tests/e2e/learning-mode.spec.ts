import { expect, test } from '@playwright/test'
import { savedChat, seedChat } from './chat-fixtures'

test('Plus and slash share one keyboard menu, retain draft, focus and conversation mode', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.chat-workspace')).toHaveAttribute('data-ready', 'true')
  const input = page.getByRole('textbox', { name: 'Nachricht', exact: true })
  await input.fill('Mein Lernziel /')
  await expect(page.locator('.composer-action-menu')).toBeVisible()
  await input.press('Escape')
  await expect(page.locator('.composer-action-menu')).toBeHidden()
  await expect(input).toHaveValue('Mein Lernziel /')
  await expect(input).toBeFocused()
  await input.fill('Mein Lernziel /lernen')
  await expect(page.locator('.composer-action-menu')).toBeVisible()
  await input.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: /^Lernen/ })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('.composer-learning')).toBeVisible()
  await expect(input).toHaveValue('Mein Lernziel ')
  await expect(input).toBeFocused()
  await expect(page.locator('.message-user')).toHaveCount(0)
  await input.fill('Vorne / hinten')
  await input.evaluate((element: HTMLTextAreaElement) => {
    element.setSelectionRange(7, 7)
    element.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await expect(page.locator('.composer-action-menu')).toBeVisible()
  await input.press('Enter')
  await expect(input).toHaveValue('Vorne  hinten')
  await expect(page.locator('.message-user')).toHaveCount(0)
  await input.fill('Mein Lernziel ')
  await page.reload()
  await expect(page.locator('.composer-learning')).toBeVisible()
  await expect(input).toHaveValue('Mein Lernziel ')
  const model = page.getByRole('button', { name: 'Modell im Eingabefeld auswählen', exact: true })
  await model.click()
  await page.getByRole('option', { name: /noris Fast/ }).click()
  await expect(page.locator('.composer-learning')).toBeVisible()
  await page.getByRole('button', { name: 'Lernmodus deaktivieren', exact: true }).click()
  await expect(page.locator('.composer-learning')).toBeHidden()
  await expect(input).toHaveValue('Mein Lernziel ')
  await page.getByRole('button', { name: 'Aktionen öffnen', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Lernen/ }).click()
  await expect(input).toBeFocused()
  await expect(page.locator('.composer-learning')).toBeVisible()
  await input.evaluate(element => { element.dataset.original = 'preserved' })
  await input.fill('Mehrere Zeilen\nmit einer Übung\nund Kontext')
  await expect(page.locator('.composer-container')).toHaveAttribute('data-layout', 'expanded')
  await input.fill('Kurz')
  await expect(page.locator('.composer-container')).toHaveAttribute('data-layout', 'compact')
  await expect(input).toHaveAttribute('data-original', 'preserved')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

for (const viewport of [{ width: 1920, height: 975 }, { width: 768, height: 1024 }, { width: 390, height: 844 }]) {
  for (const theme of ['light', 'dark']) {
    test(`learning reference ${viewport.width} ${theme}`, async ({ page }, info) => {
      test.skip(info.project.name !== 'desktop', 'Each requested viewport is captured once.')
      await page.setViewportSize(viewport)
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await seedChat(page, savedChat(), theme)
      await page.goto('/')
      await expect(page.locator('.chat-workspace')).toHaveAttribute('data-ready', 'true')
      const input = page.getByRole('textbox', { name: 'Nachricht', exact: true })
      await input.fill('/')
      await expect(page.locator('.composer-action-menu')).toBeVisible()
      const menu = (await page.locator('.composer-action-menu').boundingBox())!
      const composer = (await page.locator('.chat-composer').boundingBox())!
      expect(menu.width).toBeCloseTo(composer.width, 0)
      expect(menu.y + menu.height).toBeLessThanOrEqual(composer.y)
      await expect(page).toHaveScreenshot(`learning-${viewport.width}-${theme}-slash.png`, { animations: 'disabled', caret: 'hide' })
      await page.getByRole('menuitem', { name: /^Lernen/ }).click()
      await expect(page.locator('.composer-learning')).toBeVisible()
      await expect(page).toHaveScreenshot(`learning-${viewport.width}-${theme}-active.png`, { animations: 'disabled', caret: 'hide' })
      await page.getByRole('button', { name: 'Aktionen öffnen', exact: true }).click()
      await expect(page.getByRole('menuitem', { name: /Lernen Ausgewählt/ })).toBeVisible()
      await expect(page).toHaveScreenshot(`learning-${viewport.width}-${theme}-selected.png`, { animations: 'disabled', caret: 'hide' })
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Denkaufwand: Standard', exact: true }).click()
      await expect(page.getByRole('menuitemcheckbox', { name: /^Pro / })).toHaveAttribute('aria-disabled', 'true')
      await expect(page.getByRole('menuitemcheckbox', { name: /^Sehr hoch / })).toHaveAttribute('aria-disabled', 'true')
      await expect(page).toHaveScreenshot(`learning-${viewport.width}-${theme}-reasoning.png`, { animations: 'disabled', caret: 'hide' })
      await page.keyboard.press('Escape')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    })
  }
}
