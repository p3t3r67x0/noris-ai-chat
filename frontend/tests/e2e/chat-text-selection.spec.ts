test('native mouse selection updates only after pointer release', async ({ page }, info) => {
  test.skip(info.project.name === 'mobile', 'Mobile selection uses native touch handles and Selection API coverage.')
  await page.locator('.user-bubble').scrollIntoViewIfNeeded()
  const rect = await page.locator('.user-bubble').evaluate(element => {
    const range = document.createRange()
    range.setStart(element.firstChild!, 0); range.setEnd(element.firstChild!, 20)
    const rect = range.getBoundingClientRect()
    return { left: rect.left, right: rect.right, top: rect.top, height: rect.height }
  })
  await page.mouse.move(rect.left + 1, rect.top + rect.height / 2)
  await page.mouse.down()
  await page.mouse.move(rect.right - 1, rect.top + rect.height / 2, { steps: 5 })
  await page.waitForTimeout(200)
  await expect(page.getByRole('button', { name: 'noris AI fragen', exact: true })).toHaveCount(0)
  await page.mouse.up()
  await expect(page.getByRole('button', { name: 'noris AI fragen', exact: true })).toBeVisible()
})

