const input = (page: Page) => page.getByRole('textbox', { name: 'Nachricht', exact: true })
async function enable(page: Page): Promise<void> {
  await page.getByRole('button', { name: 'Anhänge und Werkzeuge', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Websuche/ }).click()
  await expect(page.locator('[data-research-selected]')).toBeVisible()
  await expect(page.locator('.research-privacy')).toContainText('externe Suchanbieter')
}
