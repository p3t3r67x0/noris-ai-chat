test('P7c activation survives attachment preparation and incompatible model hints preserve drafts', async ({ page }) => {
  let incompatible = false
  await page.route('**/api/v1/llm/models', async route => {
    const response = await route.fetch(), value = await response.json()
    await route.fulfill({ response, json: { ...value, expires_in_seconds: 60, models: value.models.map((model: Record<string, unknown>) => ({ ...model, research_eligible: incompatible ? false : model.research_eligible })) } })
  })
  await page.goto('/')
  await expect(page.locator('.chat-workspace')).toHaveAttribute('data-ready', 'true')
  await enable(page)
  await input(page).fill('My question stays here')
  await page.locator('input[type="file"]').setInputFiles({ name: 'context.txt', mimeType: 'text/plain', buffer: Buffer.from('Private attachment text is not a search query.') })
  await expect(page.locator('.attachment-preview')).toHaveAttribute('data-upload-status', 'uploaded')
  await expect(page.locator('[data-research-selected]')).toBeVisible()
  incompatible = true
  await page.getByRole('button', { name: 'Nachricht senden', exact: true }).click()
  await expect(page.getByText('Dieses Modell ist für Websuche nicht geeignet.', { exact: false })).toBeVisible()
  await expect(input(page)).toHaveValue('My question stays here')
  await expect(page.locator('[data-research-selected]')).toBeVisible()
  await expect(page.locator('.message-user')).toHaveCount(0)
  await page.getByRole('button', { name: 'Websuche deaktivieren', exact: true }).click()
  await expect(input(page)).toHaveValue('My question stays here')
  await expect(page.locator('.attachment-preview')).toHaveCount(1)
})

