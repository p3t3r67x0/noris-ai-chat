import { expect, test } from '@playwright/test'
import { clearTestConversations, stableModelCatalog } from './chat-fixtures'

const fixtureOrigin = `http://127.0.0.1:${process.env.NORIS_E2E_PROVIDER_PORT ?? 8591}`
test.beforeEach(async ({ page, request }) => {
  await stableModelCatalog(page)
  await clearTestConversations(request)
  await request.put('/api/v1/chat/preferences', { data: { activeConversationId: null, modelId: null } })
  await request.put('/api/v1/chat/drafts/new', { data: { content: '' } })
  await request.post(`${fixtureOrigin}/fixture/catalog`, { data: { ids: ['fixture-alpha', 'fixture-beta', 'vllm/release/gpt-oss-120b'] } })
})
test.afterEach(async ({ request }) => {
  await request.post(`${fixtureOrigin}/fixture/catalog`, { data: { ids: ['fixture-alpha', 'fixture-beta', 'fixture-long'] } })
})

test('slash actions reuse model, reasoning, search and upload boundaries without provider calls', async ({ page, request }) => {
  await page.goto('/')
  await expect(page.locator('.chat-workspace')).toHaveAttribute('data-ready', 'true')
  const input = page.getByRole('textbox', { name: 'Nachricht', exact: true })
  const menu = page.locator('.composer-slash-menu')
  const state = await (await request.get(`${fixtureOrigin}/fixture/state`)).json()
  await expect(page.getByRole('button', { name: 'Modell im Eingabefeld auswählen', exact: true })).toBeEnabled({ timeout: 15_000 })
  await input.fill('/modell')
  await input.press('Enter')
  await page.getByRole('option', { name: /GPT-OSS 120B/ }).click()
  await expect(page.getByRole('button', { name: 'Denkaufwand: Standard', exact: true })).toBeEnabled()
  await input.fill('/denken')
  await expect(menu.getByRole('option', { name: /^Denkaufwand/ })).toBeVisible()
  await input.press('Enter')
  await page.getByRole('menuitemcheckbox', { name: /^Hoch / }).click()
  await expect(page.getByRole('button', { name: 'Denkaufwand: Hoch', exact: true })).toBeEnabled()
  await input.fill('/suche')
  await input.press('Enter')
  await expect(page.locator('[data-research-selected]')).toBeVisible()
  await expect(input).toHaveValue('')
  await page.getByRole('button', { name: 'Websuche deaktivieren', exact: true }).click()
  await input.fill('Mein Thema /datei')
  const chooser = page.waitForEvent('filechooser')
  await menu.getByRole('option', { name: /^Fotos und Dateien/ }).click()
  await (await chooser).setFiles({ name: 'slash.txt', mimeType: 'text/plain', buffer: Buffer.from('Synthetic study context.') })
  await expect(page.locator('[data-upload-status="uploaded"]')).toHaveCount(1)
  await expect(input).toHaveValue('Mein Thema ')
  await input.fill('/modell')
  await input.press('Enter')
  await page.getByRole('option', { name: /Fixture Beta/ }).click()
  await input.fill('/')
  await expect(menu.getByRole('option', { name: /^Denkaufwand/ })).toHaveCount(0)
  await expect(menu.getByRole('option', { name: /^Bild erstellen/ })).toHaveCount(0)
  expect((await (await request.get(`${fixtureOrigin}/fixture/state`)).json()).calls).toHaveLength(state.calls.length)
  await expect(page.locator('.message-user')).toHaveCount(0)
})
